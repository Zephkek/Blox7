"""libc.so's version script from bionic's map files
usage: gen-version-script.py <bionic dir> <out.map>"""
import re, sys

bionic, out_path = sys.argv[1:3]
ARCHES = {'arm', 'arm64', 'x86', 'x86_64', 'riscv64', 'lp32', 'lp64'}
OURS = {'x86_64', 'lp64'}

nodes = {}
order = []
for name in ('libc/libc.map.txt', 'libm/libm.map.txt', 'libdl/libdl.map.txt'):
    node = None
    section = None
    for raw in open(f'{bionic}/{name}', encoding='utf-8'):
        line, _, comment = raw.partition('#')
        tags = set(comment.split())
        line = line.strip()
        m = re.match(r'^(\w+)\s*\{', line)
        if m:
            node = m.group(1)
            if node not in nodes:
                nodes[node] = {'globals': [], 'parent': None}
                order.append(node)
            section = None
            continue
        m = re.match(r'^\}\s*(\w+)?\s*;', line)
        if m:
            if m.group(1) and not nodes[node]['parent']:
                nodes[node]['parent'] = m.group(1)
            node = None
            continue
        if line in ('global:', 'local:'):
            section = line[:-1]
            continue
        if node is None or section != 'global' or not line.endswith(';'):
            continue
        arch_tags = tags & ARCHES
        if arch_tags and not (arch_tags & OURS):
            continue
        symbol = line[:-1].strip()
        if symbol not in nodes[node]['globals']:
            nodes[node]['globals'].append(symbol)

with open(out_path, 'w', newline='\n') as f:
    f.write('/* Generated by win/tools/gen-version-script.py from bionic\'s map files. */\n')
    first = True
    for name in order:
        n = nodes[name]
        f.write(f'{name} {{\n  global:\n')
        for s in n['globals']:
            f.write(f'    {s};\n')
        if first:
            f.write('  local:\n    *;\n')
            first = False
        f.write('}' + (f' {n["parent"]}' if n['parent'] else '') + ';\n')
    f.write('LIBC_W32 {\n  global:\n    __w32_*;\n    pthread_tryjoin_np;\n')
    f.write('    android_get_LD_LIBRARY_PATH;\n    android_update_LD_LIBRARY_PATH;\n} LIBC;\n')
print(f'{sum(len(n["globals"]) for n in nodes.values())} symbols in {len(order)} version nodes')
