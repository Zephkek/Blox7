"""compiles the etc2 decode compute shader into src/graphics/gen/etc2_decode_shader.h"""
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
NDK = os.environ.get('BLOX7_NDK', 'D:/toolchains/android-ndk-r28c')
TOOLS = f'{NDK}/shader-tools/windows-x86_64'
SOURCE = os.path.join(ROOT, 'src', 'graphics', 'shaders', 'etc2_decode.comp')
OUT = os.path.join(ROOT, 'src', 'graphics', 'gen', 'etc2_decode_shader.h')

with tempfile.TemporaryDirectory() as tmp:
    spv = os.path.join(tmp, 'etc2_decode.spv')
    subprocess.check_call([f'{TOOLS}/glslc.exe', '-O', '--target-env=vulkan1.0', '-fshader-stage=compute', SOURCE,
                           '-o', spv])
    subprocess.check_call([f'{TOOLS}/spirv-val.exe', '--target-env', 'vulkan1.0', spv])
    data = open(spv, 'rb').read()
values = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
lines = ['    ' + ', '.join(f'0x{v:08x}u' for v in values[i:i + 8]) + ',' for i in range(0, len(values), 8)]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('#pragma once\n// generated by win/tools/gen-etc2-shader.py from src/graphics/shaders/etc2_decode.comp\n'
            '#include <cstdint>\n\n')
    f.write('inline constexpr std::uint32_t kEtc2DecodeShader[] = {\n' + '\n'.join(lines) + '\n};\n')
print('wrote', OUT)
