"""the vulkan half of the sdl3 bridge: a sysv wrapper for every vulkan_core.h command
usage: gen-vulkan-bridge.py <vulkan include dir> <vk.xml> <out.c>"""
import re, sys
import xml.etree.ElementTree as ET

inc, xml_path, out_path = sys.argv[1:4]
core = open(f'{inc}/vulkan_core.h', encoding='utf-8').read()

AFTER = {'vkQueuePresentKHR': '__w32_frame_beat();'}
MANUAL = {'vkGetInstanceProcAddr', 'vkGetDeviceProcAddr', 'vkCreateInstance', 'vkCreateDevice',
          'vkCreateDebugUtilsMessengerEXT', 'vkCreateDebugReportCallbackEXT'}
DEVICE_HANDLES = {'VkDevice', 'VkQueue', 'VkCommandBuffer'}
INSTANCE_HANDLES = {'VkInstance', 'VkPhysicalDevice'}


def split_top(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


commands = []
for m in re.finditer(r'VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);', core, re.S):
    ret, name, params = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
    plist = [] if params in ('', 'void') else split_top(params)
    parsed = []
    for p in plist:
        pm = re.match(r'^(.*?)(\w+)(\s*\[[^\]]*\])?$', p)
        if not pm:
            sys.exit(f'cannot parse parameter {p!r} of {name}')
        parsed.append((p, pm.group(2), pm.group(1).strip()))
    commands.append({'name': name, 'ret': ret, 'params': parsed})
names = [c['name'] for c in commands]
assert len(set(names)) == len(names), 'duplicate prototypes'

defined = set(re.findall(r'^typedef (?:struct|union) (Vk\w+) \{', core, re.M))
stypes = []
for t in ET.parse(xml_path).getroot().iter('type'):
    if t.get('category') != 'struct' or t.get('alias') or t.get('name') not in defined:
        continue
    if t.get('api') and 'vulkan' not in t.get('api').split(','):
        continue
    for member in t.findall('member'):
        if member.findtext('name') == 'sType' and member.get('values'):
            value = member.get('values').split(',')[0]
            if re.search(r'\b' + value + r'\b', core):
                stypes.append((value, t.get('name')))
            break

out = ['// Generated by win/tools/gen-vulkan-bridge.py from vulkan_core.h and vk.xml. Do not edit.\n'
       '#include "vulkan_bridge.h"\n\n']
table = []
for c in commands:
    name, ret, params = c['name'], c['ret'], c['params']
    decls = ', '.join(p[0] for p in params) or 'void'
    first = params[0][2].replace('const', '').strip() if params else ''
    kind = 'VKB_DEVICE' if first in DEVICE_HANDLES else 'VKB_INSTANCE' if first in INSTANCE_HANDLES else 'VKB_GLOBAL'
    out.append(f'__attribute__((visibility("hidden"))) {ret} (BRIDGE_MS *vkb_ms_{name})({decls});\n')
    if name in MANUAL:
        out.append(f'{ret} vkb_m_{name}({decls});\n')
        table.append((name, f'vkb_m_{name}', 'NULL', 'NULL', kind))
        continue
    args = []
    for decl, pname, ptype in params:
        args.append(f'vkb_allocator({pname})' if ptype.replace(' ', '') == 'constVkAllocationCallbacks*' else pname)
    for prefix, slot in (('w', 'ms'), ('d', 'msd')) if kind == 'VKB_DEVICE' else (('w', 'ms'),):
        if slot == 'msd':
            out.append(f'static {ret} (BRIDGE_MS *vkb_msd_{name})({decls});\n')
        call = f'vkb_{slot}_{name}({", ".join(args)})'
        body = f'  {call};\n' if ret == 'void' else f'  return {call};\n'
        if name in AFTER:
            body = (f'  {call};\n  {AFTER[name]}\n' if ret == 'void'
                    else f'  const {ret} result = {call};\n  {AFTER[name]}\n  return result;\n')
        out.append(f'static {ret} vkb_{prefix}_{name}({decls}) {{\n{body}}}\n')
    if kind == 'VKB_DEVICE':
        table.append((name, f'vkb_w_{name}', f'(void**)&vkb_msd_{name}', f'(void*)vkb_d_{name}', kind))
    else:
        table.append((name, f'vkb_w_{name}', 'NULL', 'NULL', kind))

table.sort()
out.append('\n// sorted by name (vkb_find)\nconst struct vkb_command vkb_commands[] = {\n')
out += [f'    {{"{n}", (void**)&vkb_ms_{n}, (void*){w}, {ds}, {dw}, {k}}},\n' for n, w, ds, dw, k in table]
out.append('};\nconst size_t vkb_command_count = sizeof(vkb_commands) / sizeof(vkb_commands[0]);\n\n')
out.append('size_t vkb_struct_size(VkStructureType type) {\n  switch ((int)type) {\n')
out += [f'    case {v}: return sizeof({s});\n' for v, s in stypes]
out.append('    default: return 0;\n  }\n}\n')
with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
    f.write(''.join(out))
print(f'{len(table)} commands ({len(MANUAL)} hand-written, '
      f'{sum(1 for t in table if t[2] != "NULL")} with a driver-direct function), {len(stypes)} structure sizes')
