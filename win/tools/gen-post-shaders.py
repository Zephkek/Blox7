"""compiles the post fx shaders into win/runtime/gen/post_shaders.h"""
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
WIN = os.path.dirname(HERE)
NDK = os.environ.get('BLOX7_NDK', 'D:/toolchains/android-ndk-r28c')
GLSLC = f'{NDK}/shader-tools/windows-x86_64/glslc.exe'
SHADERS = os.path.join(WIN, 'runtime', 'shaders')
OUT = os.path.join(WIN, 'runtime', 'gen', 'post_shaders.h')


def words(path):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, 'out.spv')
        subprocess.check_call([GLSLC, '-O', '--target-env=vulkan1.0', path, '-o', spv])
        data = open(spv, 'rb').read()
    return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def array(name, values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append('    ' + ', '.join(f'0x{v:08x}u' for v in values[i:i + 8]) + ',')
    return f'inline constexpr std::uint32_t {name}[] = {{\n' + '\n'.join(lines) + '\n};\n'


os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('#pragma once\n// generated by win/tools/gen-post-shaders.py from win/runtime/shaders\n#include <cstdint>\n\n')
    f.write(array('kPostVertexShader', words(os.path.join(SHADERS, 'post.vert'))))
    f.write('\n')
    f.write(array('kPostFragmentShader', words(os.path.join(SHADERS, 'post.frag'))))
print('wrote', OUT)
