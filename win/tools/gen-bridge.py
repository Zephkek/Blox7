"""generates an android elf lib that forwards a C api to a windows dll (sysv -> ms_abi)
usage: gen-bridge.py <ast.json> <header dir>[,...] <dll> <out.c> [--manual a,b] [--hook name=fn,...]"""
import json, re, sys

ast_path, dirs, dll, out_path = sys.argv[1:5]
manual = set()
resolver = None
if '--resolver' in sys.argv:
    resolver = sys.argv[sys.argv.index('--resolver') + 1]
if '--manual' in sys.argv:
    manual = set(sys.argv[sys.argv.index('--manual') + 1].split(','))
hooks = {}
if '--hook' in sys.argv:
    hooks = dict(h.split('=') for h in sys.argv[sys.argv.index('--hook') + 1].split(','))
dirs = [d.replace('\\', '/') for d in dirs.split(',')]

tu = json.load(open(ast_path, encoding='utf-8'))

functions, typedefs = [], {}
cur_file = ''
for node in tu.get('inner', []):
    loc = node.get('loc', {})
    f = loc.get('file') or loc.get('expansionLoc', {}).get('file') or loc.get('spellingLoc', {}).get('file')
    if f:
        cur_file = f.replace('\\', '/')
    in_api = any(d in cur_file for d in dirs)
    if node.get('kind') == 'TypedefDecl':
        typedefs[node['name']] = node['type'].get('desugaredQualType', node['type']['qualType'])
    if not in_api or node.get('kind') != 'FunctionDecl' or node.get('isImplicit'):
        continue
    if node.get('storageClass') == 'static' or node.get('inline') or any(c.get('kind') == 'CompoundStmt' for c in node.get('inner', [])):
        continue
    params = [(p.get('name') or f'a{i}', p['type']['qualType'], p['type'].get('desugaredQualType', p['type']['qualType']))
              for i, p in enumerate(c for c in node.get('inner', []) if c.get('kind') == 'ParmVarDecl')]
    qual = node['type']['qualType']
    functions.append({'name': node['name'], 'type': qual, 'params': params, 'variadic': node.get('variadic', False)})


def split_top(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def return_type(fn_type):
    depth = 0
    for i in range(len(fn_type) - 1, -1, -1):
        if fn_type[i] == ')':
            depth += 1
        elif fn_type[i] == '(':
            depth -= 1
            if depth == 0:
                return fn_type[:i].strip()
    raise ValueError(fn_type)


FN_PTR = re.compile(r'^(.*?)\(\*\)\((.*)\)$')


def fn_pointer_sig(t):
    """(ret, [params]) for a function pointer type, else None"""
    t = t.strip()
    m = FN_PTR.match(t)
    if not m:
        return None
    ret, params = m.group(1).strip(), m.group(2).strip()
    params = [] if params in ('', 'void') else split_top(params)
    return ret, params


def declare(t, name):
    """declares `name` as C type `t`, arrays and function pointers too"""
    m = re.match(r'^(.*?)\(\*\)(.*)$', t)
    if m:
        return f'{m.group(1)}(*{name}){m.group(2)}'
    m = re.match(r'^(.*?)(\[\d*\])+$', t)
    if m:
        return f'{m.group(1).strip()} *{name}'
    return f'{t} {name}'


def resolved(t):
    """callback typedefs expanded one level"""
    base = t.replace('const ', '').strip()
    return typedefs.get(base, t)


callbacks = {}
out = []
out.append(f'// Generated by win/tools/gen-bridge.py: forwards to {dll}. Do not edit.\n')
includes = sys.argv[sys.argv.index('--include') + 1].split(',') if '--include' in sys.argv else []
out.append(''.join(f'#include <{h}>\n' for h in includes) + '#include "bridge_common.h"\n\n')
skipped = []
entries = []
for fn in functions:
    name = fn['name']
    if name in manual:
        continue
    ptypes = [p[1] for p in fn['params']]
    if fn['variadic'] or any('va_list' in t or '__va_list' in t for t in ptypes):
        skipped.append((name, 'variadic'))
        continue
    ret = return_type(fn['type'])
    plan = []
    ok = True
    for i, (pname, ptype, desugared) in enumerate(fn['params']):
        sig = fn_pointer_sig(desugared) or fn_pointer_sig(resolved(ptype))
        if not sig:
            plan.append(('plain',))
            continue
        cb_ret, cb_params = sig
        ud = next((k for k, p in enumerate(fn['params']) if k != i and p[0] in ('userdata', 'data', 'user_data', 'arg') and
                   p[1].replace(' ', '') in ('void*', 'void *'.replace(' ', ''))), None)
        if not cb_params or cb_params[0].replace(' ', '') != 'void*' or ud is None:
            ok = False
            break
        plan.append(('callback', sig, ud, ptype))
    if not ok or fn_pointer_sig(ret) or (ret in typedefs and fn_pointer_sig(typedefs[ret])):
        skipped.append((name, 'callback shape'))
        continue
    shared = [p[2] for p in plan if p[0] == 'callback']
    if len(shared) != len(set(shared)):
        skipped.append((name, 'shared userdata'))
        continue
    userdata_of = {p[2]: i for i, p in enumerate(plan) if p[0] == 'callback'}
    pnames = [f'a{i}' for i in range(len(fn['params']))]
    proto_params = ', '.join(declare(t, n) for (pn, t, d), n in zip(fn['params'], pnames)) or 'void'
    ms_params = ', '.join(t for pn, t, d in fn['params']) or 'void'
    ptr = f'p_{name}'
    out.append(f'static {ret} (BRIDGE_MS *{ptr})({ms_params});\n')
    args = []
    pre = []
    for i, p in enumerate(plan):
        if p[0] == 'callback':
            cb_ret, cb_params = p[1]
            key = re.sub(r'\W+', '_', p[3]).strip('_')
            callbacks[key] = (cb_ret, cb_params)
            pre.append(f'  void *t{i} = a{i} ? (void *)tramp_{key} : 0;\n'
                       f'  void *c{i} = a{i} ? bridge_context((void *)a{i}, a{p[2]}) : a{p[2]};\n')
            args.append(f'({p[3]})t{i}')
        elif i in userdata_of:
            args.append(f'c{userdata_of[i]}')
        else:
            args.append(pnames[i])
    call = f'{ptr}({", ".join(args)})'
    if name in hooks:
        hook_params = '' if proto_params == 'void' else f', {proto_params}'
        out.append(f'{ret} {hooks[name]}({ret} (BRIDGE_MS *)({ms_params}){hook_params});\n')
        call = f'{hooks[name]}({", ".join([ptr] + args)})'
    body = ''.join(pre) + (f'  {call};\n' if ret == 'void' else f'  return {call};\n')
    out.append(f'BRIDGE_EXPORT {ret} {name}({proto_params}) {{\n{body}}}\n')
    entries.append(name)

tramps = ['// Callback trampolines: Windows calls these with the Microsoft x64 convention.\n']
for key, (cb_ret, cb_params) in callbacks.items():
    rest = cb_params[1:]
    params = ', '.join(['void *ctx'] + [declare(t, f'b{i}') for i, t in enumerate(rest)])
    call_args = ', '.join(['c->userdata'] + [f'b{i}' for i in range(len(rest))])
    fn_type = f'{cb_ret} (*)({", ".join(cb_params)})'
    call = f'(({fn_type})c->fn)({call_args})'
    body = '  bridge_attach();\n  struct bridge_context *c = (struct bridge_context *)ctx;\n'
    body += f'  {call};\n' if cb_ret == 'void' else f'  return {call};\n'
    tramps.append(f'static BRIDGE_MS {cb_ret} tramp_{key}({params}) {{\n{body}}}\n')

table = ['\nstatic const struct bridge_entry kEntries[] = {\n']
table += [f'    {{"{n}", (void **)&p_{n}}},\n' for n in entries]
table.append('};\n\n')
if resolver:
    table.append(f'BRIDGE_EXPORT void {resolver}(void *(*lookup)(const char *)) {{\n'
                 f'  for (size_t i = 0; i < sizeof(kEntries) / sizeof(kEntries[0]); i++) *kEntries[i].slot = lookup(kEntries[i].name);\n}}\n')
    table.append('\nstatic const struct { const char *name; void *fn; } kExports[] = {\n')
    table += [f'    {{"{n}", (void *){n}}},\n' for n in entries]
    table.append('};\n\n')
    table.append(f'BRIDGE_EXPORT void *{resolver}_export(const char *name) {{\n'
                 f'  for (size_t i = 0; i < sizeof(kExports) / sizeof(kExports[0]); i++)\n'
                 f'    if (strcmp(kExports[i].name, name) == 0) return kExports[i].fn;\n  return 0;\n}}\n')
else:
    table.append(f'BRIDGE_INIT("{dll}", kEntries)\n')

with open(out_path, 'w', newline='\n') as f:
    f.write(out[0] + out[1])
    f.write(''.join(tramps) + '\n')
    f.write(''.join(out[2:]))
    f.write(''.join(table))
print(f'{len(entries)} functions forwarded, {len(callbacks)} callback types, {len(skipped)} left out:')
print(' '.join(f'{n}({why})' for n, why in skipped))
