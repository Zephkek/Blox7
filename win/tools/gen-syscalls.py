"""bionic syscall stubs that call sys_<name>() instead of doing a real `syscall`
usage: gen-syscalls.py <SYSCALLS.TXT> <unistd_64.h> <out.cpp> <out.h>"""
import re, sys

syscalls_txt, unistd, out_cpp, out_h = sys.argv[1:5]

numbers = {}
for line in open(unistd):
    m = re.match(r'#define __NR_(\w+)\s+(\d+)', line)
    if m:
        numbers[m.group(1)] = int(m.group(2))

stubs = []
for raw in open(syscalls_txt):
    line = raw.split('#', 1)[0].strip()
    if not line:
        continue
    m = re.match(r'(.+?)\s*\((.*)\)\s+(\S+)\s*$', line)
    head, params, arches = m.groups()
    if not ({'all', 'lp64', 'x86_64'} & set(arches.split(','))):
        continue
    hm = re.match(r'.*?([\w|]+)(?::(\w+))?$', head)
    names, sysname = hm.group(1).split('|'), hm.group(2) or hm.group(1).split('|')[0]
    params = params.strip()
    argc = 0 if params in ('', 'void') else params.count(',') + 1
    stubs.append((names, sysname, argc))

ARGS = ['a0', 'a1', 'a2', 'a3', 'a4', 'a5']
SIX = ', '.join(f'long {a}' for a in ARGS)
used = sorted({s for _, s, _ in stubs} | set(numbers))

with open(out_h, 'w', newline='\n') as h:
    h.write('// Generated by win/tools/gen-syscalls.py. Linux system calls, implemented on Windows.\n')
    h.write('// Each returns its result, or -errno.\n#pragma once\n\n#ifdef __cplusplus\nextern "C" {\n#endif\n')
    for name in used:
        h.write(f'long sys_{name}(long a0, long a1, long a2, long a3, long a4, long a5);\n')
    h.write('// By Linux x86_64 number; returns -errno like the kernel, where syscall(2) sets errno.\n')
    h.write('long __w32_syscall_raw(long nr, long a0, long a1, long a2, long a3, long a4, long a5);\n')
    h.write('#ifdef __cplusplus\n}\n#endif\n')

with open(out_cpp, 'w', newline='\n') as c:
    c.write('// Generated by win/tools/gen-syscalls.py from SYSCALLS.TXT and unistd_64.h.\n')
    c.write('#include <errno.h>\n#include "w32_syscalls.h"\n\n')
    c.write('long __set_errno_internal(int);\nlong __w32_enosys(const char* name);\n')
    c.write('#define W32_RESULT(r) ((unsigned long)(r) > -4096UL ? __set_errno_internal((int)-(r)) : (r))\n\n')
    for name in used:
        c.write(f'__attribute__((weak)) long sys_{name}({SIX}) {{ return __w32_enosys("{name}"); }}\n')
    c.write('\n')
    for names, sysname, argc in stubs:
        params = ', '.join(f'long {a}' for a in ARGS[:argc]) or 'void'
        call = ', '.join(ARGS[:argc] + ['0'] * (6 - argc))
        c.write(f'long {names[0]}({params}) {{\n  long r = sys_{sysname}({call});\n'
                f'  return W32_RESULT(r);\n}}\n')
        for alias in names[1:]:
            c.write(f'__strong_alias({alias}, {names[0]});\n')
    c.write('\n// syscall(2): by Linux x86_64 number\n')
    c.write('typedef long (*sys_fn)(long, long, long, long, long, long);\n')
    top = max(numbers.values()) + 1
    c.write(f'static const sys_fn kSyscalls[{top}] = {{\n')
    for name, nr in sorted(numbers.items(), key=lambda kv: kv[1]):
        c.write(f'  [{nr}] = sys_{name},\n')
    c.write('};\n\n')
    c.write('long __w32_syscall_raw(long nr, long a0, long a1, long a2, long a3, long a4, long a5) {\n')
    c.write(f'  return (nr >= 0 && nr < {top} && kSyscalls[nr]) ? kSyscalls[nr](a0, a1, a2, a3, a4, a5) : -ENOSYS;\n}}\n\n')
    c.write('long syscall(long nr, long a0, long a1, long a2, long a3, long a4, long a5) {\n')
    c.write('  long r = __w32_syscall_raw(nr, a0, a1, a2, a3, a4, a5);\n')
    c.write('  return W32_RESULT(r);\n}\n')

print(f'{len(stubs)} stubs, {len(numbers)} syscall numbers')
